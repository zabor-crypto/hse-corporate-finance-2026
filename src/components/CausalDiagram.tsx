export function CausalDiagram({ kind }: { kind: "cash" | "dupont" }) {
  const cash = kind === "cash";
  const labels = cash
    ? [
        "Выручка − операционные расходы",
        "EBIT × (1 − T) → NOPAT",
        "+ амортизация − ΔNWC → операционный поток до финансирования",
        "− CapEx → FCFF",
      ]
    : [
        "NI / Sales → чистая маржа",
        "× Sales / Assets → оборот активов",
        "× Assets / Equity → мультипликатор собственного капитала",
        "= NI / Equity → ROE",
      ];
  return (
    <figure className="causal-diagram">
      <figcaption>
        {cash
          ? "От прибыли к потоку для всех поставщиков капитала"
          : "DuPont: три причины изменения ROE"}
      </figcaption>
      <ol>
        {labels.map((x, i) => (
          <li key={x}>
            <span>{i + 1}</span>
            {x}
            {i < labels.length - 1 && <b aria-hidden="true">↓</b>}
          </li>
        ))}
      </ol>
      <p>
        {cash
          ? "Начисленная выручка не равна деньгам: рост ΔNWC уменьшает поток. Амортизация возвращается, поскольку сама не требует выплаты в текущем периоде. CFO в учебнике считается от NI и включает проценты по принятой конвенции. Здесь показан поток до финансирования для вывода FCFF."
          : "Мультипликатор A/E не равен 1 + D/E при наличии беспроцентных обязательств. Высокий ROE может возникнуть из-за малого собственного капитала. Меняйте один фактор при прочих равных; причинный эффект долга требует также учитывать проценты, налог и риск."}
      </p>
    </figure>
  );
}
