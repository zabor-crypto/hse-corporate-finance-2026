export function calibrateLegacyProblem(p: Problem): Problem {
  const audit = legacyAssessmentAudit.find((a) => a.id === p.id);
  if (!audit) return p;
  const diagnostics = (choiceDiagnostics[p.id] ?? []).map((message, i) => ({
    code: `OPTION_${String.fromCharCode(65 + i)}`,
    message,
  }));
  const reasoning = p.reasoning ??
    foundationReasoning[p.id] ?? {
      prompt:
        "Объясните, почему выбранные числитель, база или денежные знаки соответствуют вопросу. Назовите одну конкретную неправильную альтернативу и исправьте её.",
      rubric: [
        "Указать экономическое значение найденного результата.",
        "Показать причинную связь хотя бы одного шага, а не повторить число.",
        "Разобрать один типичный неправильный подход из обратной связи.",
        "Уточнить период и денежный масштаб; не делать более сильного вывода, чем допускают исходные данные.",
      ],
      sampleAnswer: `${p.solution.join(" ")} Числовой или выбранный ответ сам по себе не подтверждает понимание: объяснение сопоставляется с рубрикой отдельно.`,
    };
  return {
    ...p,
    difficulty: audit.level,
    independent: {
      prompt: audit.independentPrompt ?? p.prompt,
      stageIds: audit.finalStages ?? p.stages.map((s) => s.id),
    },
    commonErrors: [...p.commonErrors, ...diagnostics],
    reasoning,
  };
}
