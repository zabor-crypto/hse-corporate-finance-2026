import type { Problem } from "../types";
import {
  draftBase,
  identity,
  stage,
  source,
  fmt,
  money,
  pct,
  type ScenarioIdentity,
} from "./shared";
export interface PayoutScenario {
  story: string;
  roc: number;
  debtEquity: number;
  debtRate: number;
  tax: number;
  ni0: number;
  payout0: number;
  payout1: number;
  equityRate: number;
}
export function makePayoutProblem(
  x: PayoutScenario,
  meta: ScenarioIdentity,
): Problem {
  const debtAfterTax = x.debtRate * (1 - x.tax),
    roe = x.roc + x.debtEquity * (x.roc - debtAfterTax);
  const g0 = (1 - x.payout0) * roe,
    g1 = (1 - x.payout1) * roe;
  if (x.equityRate <= g0 || x.equityRate <= g1)
    throw new RangeError(
      "Бессрочная модель требует rₑ > g для обоих сценариев",
    );
  const div0 = x.ni0 * (1 + g0) * x.payout0,
    div1 = x.ni0 * (1 + g1) * x.payout1;
  const price0 = div0 / (x.equityRate - g0),
    price1 = div1 / (x.equityRate - g1);
  const prompt = `${x.story} Нужна условная оценка всех обыкновенных акций на начало прогнозного периода. Историческая прибыль последнего завершённого года ${x.ni0} млн ₽ служит NI₀. Операционная доходность gross-капитала ${fmt(x.roc * 100)}% годовых, отношение долга к собственному капиталу ${fmt(x.debtEquity)}, цена долга до налога ${fmt(x.debtRate * 100)}%, налог ${fmt(x.tax * 100)}%. Доходности ROC и ROE сопоставлены с gross-капиталом и Equity на начало соответствующего года; Capital=E+D, проценты начислены на долг начала года. Прочих статей нет, налоговый щит полностью используется. Базовая доля прибыли, выплачиваемая дивидендами, ${fmt(x.payout0 * 100)}%; альтернативная — ${fmt(x.payout1 * 100)}%. Для каждого сценария принимается постоянный ROE; удержанная прибыль пополняет Equity на конец года, который становится базой следующего года, а финансирование пропорционально поддерживает D/E. Внешних выпусков акций нет. Это две устойчивые модельные траектории с одинаковым NI₀, а не реконструкция мгновенной рыночной реакции на смену политики. Прибыль и дивиденды со следующего года растут постоянным темпом; вся удержанная доля реинвестируется с тем же ROE. Дивиденд первого прогнозного года рассчитывается из выросшей прибыли этого года. Требуемая доходность собственного капитала ${fmt(x.equityRate * 100)}% в год условно фиксирована для сравнения; из изменения риска её неизменность не следует. Найдите ROE, долгосрочный темп роста при новой политике и стоимость акций при каждой политике. Объясните, какие предпосылки сделали оценку возможной и почему это не рекомендация изменить выплаты.`;
  return {
    ...draftBase,
    ...identity(meta),
    topicId: "T3-09",
    lessonId: "T3-06",
    title: "Дивиденды сегодня и прибыль следующего года",
    type: "steps",
    difficulty: "L4",
    objective:
      "Согласовать рычаг, удержанную прибыль, временную точку дивиденда и допустимость бессрочной оценки.",
    prompt,
    independent: {
      prompt,
      stageIds: ["roe", "growth-new", "equity-value-old", "equity-value-new"],
    },
    inputs: [],
    assumptions: [
      "Это ограниченная модельная задача темы 3.9, а не заявление о завершении урока T3-09.",
      "Все ставки годовые и заданы долями одного и того же периода; ROC, ROE, D/E и проценты используют согласованные начальные базы.",
      "NI₀ — прибыль прошлого года, а дивиденд в числителе цены — DIV₁.",
      "ROE, D/E и требуемая доходность в сценариях условно постоянны; эмиссии Equity нет.",
      "В каждом сценарии rₑ > g. Рыночная переоценка риска не моделируется.",
    ],
    stages: [
      stage(
        "roe",
        "Доходность собственного капитала",
        roe * 100,
        pct,
        "Восстановите, какой результат остаётся собственникам после посленалоговой цены долга.",
        `${fmt(x.roc * 100)}%+${fmt(x.debtEquity)}×(${fmt(x.roc * 100)}%−${fmt(debtAfterTax * 100)}%)=${fmt(roe * 100)}%.`,
        "DOUBLE_TAX_SHIELD",
      ),
      stage(
        "growth-old",
        "Долгосрочный рост при исходной политике",
        g0 * 100,
        pct,
        "Не вся прибыль реинвестируется: удержанная доля дополняет payout до единицы.",
        `(1−${x.payout0})×${fmt(roe)}=${fmt(g0 * 100)}%.`,
        "PAYOUT_VS_RETENTION",
      ),
      stage(
        "growth-new",
        "Долгосрочный рост при новой политике",
        g1 * 100,
        pct,
        "Выбранная доля выплат меняет долю прибыли, которая создаёт следующий прирост.",
        `(1−${x.payout1})×${fmt(roe)}=${fmt(g1 * 100)}%.`,
        "PAYOUT_VS_RETENTION",
      ),
      stage(
        "dividend-next-old",
        "Дивиденд первого прогнозного года: исходный",
        div0,
        money,
        "NI₀ ещё не является прибылью прогнозного года.",
        `${x.ni0}×(1+${fmt(g0)})×${x.payout0}=${fmt(div0)}.`,
        "DIVIDEND_TIMING",
      ),
      stage(
        "dividend-next-new",
        "Дивиденд первого прогнозного года: новый",
        div1,
        money,
        "Новая прибыль и новая доля выплат должны относиться к одному году.",
        `${x.ni0}×(1+${fmt(g1)})×${x.payout1}=${fmt(div1)}.`,
        "DIVIDEND_TIMING",
      ),
      stage(
        "equity-value-old",
        "Стоимость всех акций: исходная политика",
        price0,
        money,
        "Дисконтируется поток после даты оценки; проверьте положительность разности ставки и роста.",
        `${fmt(div0)}/(${x.equityRate}−${fmt(g0)})=${fmt(price0)}.`,
        "GORDON_DOMAIN",
      ),
      stage(
        "equity-value-new",
        "Стоимость всех акций: новая политика",
        price1,
        money,
        "Не сохраняйте старый дивиденд или старый g при переходе к новой политике.",
        `${fmt(div1)}/(${x.equityRate}−${fmt(g1)})=${fmt(price1)}.`,
        "POLICY_SCENARIO_MIX",
      ),
    ],
    formulaIds: ["roe-leverage", "growth-retention", "gordon-next-dividend"],
    sourceRefs: [
      source.lecture(79, 82, 89),
      source.seminar("3.8"),
      source.seminar("3.9"),
      source.original,
    ],
    commonErrors: [
      {
        code: "PAYOUT_VS_RETENTION",
        message:
          "Payout — выплаченная часть. Для роста используется удержанная часть 1−payout, а не сам payout.",
      },
      {
        code: "DIVIDEND_TIMING",
        message:
          "Для оценки в начале прогнозного периода нужен DIV₁. При данном условии NI₀ сначала растёт, затем из NI₁ выплачивается дивиденд.",
      },
      {
        code: "GORDON_DOMAIN",
        message:
          "При rₑ≤g конечной положительной бессрочной оценки эта модель не даёт. Отрицательный знаменатель нельзя принять за дешёвую акцию.",
      },
      {
        code: "POLICY_SCENARIO_MIX",
        message:
          "Изменение выплат требует заново согласовать g, NI₁ и DIV₁. Нельзя соединить дивиденд одной политики с ростом другой.",
      },
    ],
    solution: [
      `Цена долга после налога=${fmt(debtAfterTax * 100)}%; ROE=${fmt(roe * 100)}%.`,
      `В модели удержанная прибыль создаёт рост: g=(1−payout)×ROE. Исходный g=${fmt(g0 * 100)}%, новый=${fmt(g1 * 100)}%.`,
      `При исходной политике NI₁=NI₀(1+g), DIV₁=${fmt(div0)}; при новой DIV₁=${fmt(div1)} млн ₽.`,
      `Бессрочная сумма дисконтированных дивидендов даёт P₀=DIV₁/(rₑ−g), когда rₑ>g. Получены ${fmt(price0)} и ${fmt(price1)} млн ₽.`,
      `Разность оценок=${fmt(price1 - price0)} млн ₽ при фиксированных предпосылках. Проверка: P₀(rₑ−g) возвращает DIV₁ отдельно в каждом сценарии. Не включён возможный дивиденд DIV₀ на уже завершённую дату.`,
      "Снижение выплат не гарантирует создания стоимости в реальности: изменяются доступность проектов, ROE, потребность в финансировании и цена риска. Приближение g к rₑ делает оценку крайне чувствительной; эта задача не оценивает рыночную реакцию.",
    ],
    reasoning: {
      prompt:
        "Что означает полученная разность цен и какой вывод нельзя из неё делать? Покажите одну проверку времени и одну проверку применимости.",
      rubric: [
        "Отделить gross ROC от ROE и применить налог к цене долга только один раз.",
        "Получить growth из удержанной доли и того же ROE.",
        "Явно использовать DIV₁, а не DIV₀.",
        "Проверить rₑ>g в обоих сценариях и отметить чувствительность знаменателя.",
        "Не назвать модельный прирост цены доказательством выгодности сокращения выплат или одобрением нового риска.",
      ],
      sampleAnswer: `При сохранённых ROE и rₑ условные цены составили ${fmt(price0)} и ${fmt(price1)} млн ₽. Это результат двух согласованных сценариев дивидендов, а не доказательство причинной рыночной выгоды. Проверяю DIV₁ из выросшей NI₁ и проверяю положительный разрыв rₑ−g. В реальном решении надо заново оценить проекты, финансирование и риск.`,
    },
  };
}
